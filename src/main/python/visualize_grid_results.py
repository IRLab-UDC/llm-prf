#!/usr/bin/env python3

import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import numpy as np
import sys
import subprocess
from pathlib import Path


def get_results_dir(collection_name=None):
    script_dir = Path(__file__).parent.parent / "scripts"
    config_script = script_dir / "dataset_config.sh"

    if config_script.exists():
        cmd = f'source "{config_script}" && echo "$FOLDER"'
        result = subprocess.run(
            ["bash", "-c", cmd], capture_output=True, text=True, check=True
        )
        base_folder = Path(result.stdout.strip())
        return base_folder / "grid_results" / collection_name


# Parse command line arguments
collection_name = None
if len(sys.argv) > 1:
    if sys.argv[1] in ["-h", "--help"]:
        print("Usage: python3 visualize_grid_results.py [collection_name]")
        print("\nGenerates plots from grid search results.")
        print("If no collection_name is provided, uses default configuration.")
        sys.exit(0)
    else:
        collection_name = sys.argv[1]
        print(f"Using collection: {collection_name}")
else:
    print("No collection specified, using default configuration")

# Configuration
RESULTS_DIR = get_results_dir(collection_name)
PLOTS_DIR = RESULTS_DIR / "plots"

# Create plots directory
PLOTS_DIR.mkdir(parents=True, exist_ok=True)

# Set style
sns.set_style("whitegrid")
plt.rcParams["figure.figsize"] = (12, 8)


def load_data():
    """Load the 3 summary files generated by evaluate_grid_results.sh."""
    data = {}

    # Expected files
    files = {
        "baseline": RESULTS_DIR / "baseline.tsv",
        "monot5": RESULTS_DIR / "monot5.tsv",
        "prf": RESULTS_DIR / "prf.tsv",
    }

    for key, filepath in files.items():
        if filepath.exists():
            try:
                df = pd.read_csv(filepath, sep="\t")
                if len(df) > 0:
                    data[key] = df
                    print(
                        f"✓ Loaded {len(df)} {key} configurations from {filepath.name}"
                    )
            except Exception as e:
                print(f"Warning: Could not load {filepath}: {e}")
        else:
            print(f"Warning: File not found: {filepath}")

    if len(data) == 0:
        print("Error: No summary files could be loaded")
        print("Please run evaluate_grid_results.sh first")
        sys.exit(1)

    return data


def plot_baseline_comparison(baseline_df, metric="map", dataset=""):
    """Plot comparison between LMDirichlet and BM25 baselines."""
    if baseline_df is None or len(baseline_df) == 0:
        return

    plt.figure(figsize=(8, 6))

    baselines = baseline_df["baseline"].unique()
    values = []
    colors = ["#808080", "#4ECDC4"]

    for baseline in baselines:
        val = baseline_df[baseline_df["baseline"] == baseline][metric].iloc[0]
        values.append(val)

    bars = plt.bar(
        baselines,
        values,
        color=colors[: len(baselines)],
        alpha=0.7,
        edgecolor="black",
        linewidth=1.5,
    )

    # Add value labels on bars
    for bar, val in zip(bars, values):
        plt.text(
            bar.get_x() + bar.get_width() / 2.0,
            bar.get_height(),
            f"{val:.4f}",
            ha="center",
            va="bottom",
            fontsize=12,
            fontweight="bold",
        )

    plt.ylabel(metric.upper(), fontsize=12)
    plt.title(f"Baseline Models Comparison ({metric.upper()})", fontsize=14)
    if dataset:
        plt.title(
            f"Baseline Models Comparison - {dataset} ({metric.upper()})", fontsize=14
        )

    plt.grid(axis="y", alpha=0.3)
    plt.tight_layout()
    plt.savefig(
        PLOTS_DIR / f"baseline_comparison_{metric}.png", dpi=300, bbox_inches="tight"
    )
    plt.close()


def plot_monot5_depth_analysis(monot5_df, metric="map", dataset=""):
    """Plot MonoT5 performance by depth for each baseline."""
    if monot5_df is None or len(monot5_df) == 0:
        return

    plt.figure(figsize=(10, 6))

    for baseline in monot5_df["baseline"].unique():
        subset = monot5_df[monot5_df["baseline"] == baseline]
        subset = subset.sort_values("depth")
        plt.plot(
            subset["depth"],
            subset[metric],
            marker="o",
            linewidth=2,
            label=f"{baseline}",
            markersize=8,
        )

    plt.xlabel("Depth (k)", fontsize=12)
    plt.ylabel(metric.upper(), fontsize=12)
    plt.title(f"MonoT5 Reranking Performance by Depth ({metric.upper()})", fontsize=14)
    if dataset:
        plt.title(f"MonoT5 Reranking - {dataset} ({metric.upper()})", fontsize=14)

    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(PLOTS_DIR / f"monot5_depth_{metric}.png", dpi=300, bbox_inches="tight")
    plt.close()


def plot_prf_lambda_impact(prf_df, metric="map", dataset=""):
    """Plot impact of lambda on PRF performance."""
    if prf_df is None or len(prf_df) == 0:
        return

    # Plot for each strategy and RF model combination
    for strategy in prf_df["strategy"].unique():
        for rf_model in prf_df["rf_model"].unique():
            subset = prf_df[
                (prf_df["strategy"] == strategy) & (prf_df["rf_model"] == rf_model)
            ]
            if len(subset) == 0:
                continue

            plt.figure(figsize=(12, 8))

            # Plot lines for different depth/e combinations
            for baseline in subset["baseline"].unique():
                base_subset = subset[subset["baseline"] == baseline]
                for depth in sorted(base_subset["depth"].unique()):
                    for e in sorted(base_subset["e"].unique()):
                        params_subset = base_subset[
                            (base_subset["depth"] == depth) & (base_subset["e"] == e)
                        ]
                        if len(params_subset) > 0:
                            params_subset = params_subset.sort_values("lambda")
                            plt.plot(
                                params_subset["lambda"],
                                params_subset[metric],
                                marker="o",
                                alpha=0.7,
                                label=f"{baseline}, d={depth}, e={e}",
                            )

            plt.xlabel("Lambda (interpolation weight)", fontsize=12)
            plt.ylabel(metric.upper(), fontsize=12)
            plt.title(
                f"PRF {strategy} + {rf_model}: Lambda Impact ({metric.upper()})",
                fontsize=14,
            )
            if dataset:
                plt.suptitle(f"{dataset}", fontsize=12)
            plt.legend(bbox_to_anchor=(1.05, 1), loc="upper left", fontsize=8)
            plt.grid(True, alpha=0.3)
            plt.tight_layout()
            plt.savefig(
                PLOTS_DIR / f"prf_{strategy}_{rf_model}_lambda_{metric}.png",
                dpi=300,
                bbox_inches="tight",
            )
            plt.close()


def plot_prf_rf_model_comparison(prf_df, metric="map", dataset=""):
    """Compare RM3 vs DMM vs MEDMM for each strategy."""
    if prf_df is None or len(prf_df) == 0:
        return

    for strategy in prf_df["strategy"].unique():
        strategy_subset = prf_df[prf_df["strategy"] == strategy]

        plt.figure(figsize=(10, 6))

        # Get best config for each RF model
        rf_models = []
        values = []
        configs = []
        colors = ["#FF6B6B", "#4ECDC4", "#45B7D1"]

        for rf_model in sorted(strategy_subset["rf_model"].unique()):
            rf_subset = strategy_subset[strategy_subset["rf_model"] == rf_model]
            best = rf_subset.loc[rf_subset[metric].idxmax()]

            rf_models.append(rf_model)
            values.append(best[metric])
            configs.append(f"k={best['depth']}, e={best['e']}, λ={best['lambda']:.2f}")

        bars = plt.bar(
            rf_models,
            values,
            color=colors[: len(rf_models)],
            alpha=0.7,
            edgecolor="black",
            linewidth=1.5,
        )

        # Add value labels and config info
        for bar, val, config in zip(bars, values, configs):
            plt.text(
                bar.get_x() + bar.get_width() / 2.0,
                bar.get_height(),
                f"{val:.4f}",
                ha="center",
                va="bottom",
                fontsize=11,
                fontweight="bold",
            )
            plt.text(
                bar.get_x() + bar.get_width() / 2.0,
                bar.get_height() * 0.5,
                config,
                ha="center",
                va="center",
                fontsize=9,
                bbox=dict(boxstyle="round,pad=0.3", facecolor="white", alpha=0.8),
            )

        plt.ylabel(metric.upper(), fontsize=12)
        plt.title(f"RF Models Comparison - {strategy} ({metric.upper()})", fontsize=14)
        if dataset:
            plt.title(
                f"RF Models Comparison - {strategy} - {dataset} ({metric.upper()})",
                fontsize=14,
            )

        plt.grid(axis="y", alpha=0.3)
        plt.tight_layout()
        plt.savefig(
            PLOTS_DIR / f"rf_models_comparison_{strategy}_{metric}.png",
            dpi=300,
            bbox_inches="tight",
        )
        plt.close()


def plot_overall_comparison(data, metric="map", dataset=""):
    """Plot comparison of best configurations across all methods."""
    plt.figure(figsize=(14, 8))

    methods = []
    values = []
    colors = []
    configs = []

    # Baseline models
    if "baseline" in data:
        for baseline in data["baseline"]["baseline"].unique():
            subset = data["baseline"][data["baseline"]["baseline"] == baseline]
            val = subset[metric].iloc[0]
            methods.append(f"Baseline\n{baseline}")
            values.append(val)
            colors.append("#808080" if baseline == "LMDirichlet" else "#4ECDC4")
            configs.append("")

    # MonoT5 reranking - best for each baseline
    if "monot5" in data:
        for baseline in data["monot5"]["baseline"].unique():
            subset = data["monot5"][data["monot5"]["baseline"] == baseline]
            best = subset.loc[subset[metric].idxmax()]
            methods.append(f"MonoT5\n{baseline}")
            values.append(best[metric])
            colors.append("#FF6B6B")
            configs.append(f"depth={best['depth']}")

    # PRF - best for each strategy + RF model combination
    if "prf" in data:
        strategy_colors = {
            "prf": "#45B7D1",
            "ORACLE": "#98D8C8",
            "MONOT5": "#AF7AC5",
            "VLLM": "#F39C12",
        }

        for strategy in data["prf"]["strategy"].unique():
            for rf_model in data["prf"]["rf_model"].unique():
                subset = data["prf"][
                    (data["prf"]["strategy"] == strategy)
                    & (data["prf"]["rf_model"] == rf_model)
                ]
                if len(subset) > 0:
                    best = subset.loc[subset[metric].idxmax()]
                    methods.append(f"PRF {strategy}\n{rf_model}")
                    values.append(best[metric])
                    colors.append(strategy_colors.get(strategy, "#2ECC71"))
                    configs.append(
                        f"k={best['depth']}, e={best['e']}, λ={best['lambda']:.1f}"
                    )

    # Create bar plot
    x_pos = np.arange(len(methods))
    bars = plt.bar(
        x_pos, values, color=colors, alpha=0.7, edgecolor="black", linewidth=1.5
    )

    # Add value labels
    for bar, val in zip(bars, values):
        plt.text(
            bar.get_x() + bar.get_width() / 2.0,
            bar.get_height(),
            f"{val:.4f}",
            ha="center",
            va="bottom",
            fontsize=10,
            fontweight="bold",
        )

    # Add configuration info below bars
    for i, config in enumerate(configs):
        if config:
            plt.text(
                i,
                values[i] * 0.1,
                config,
                ha="center",
                va="bottom",
                fontsize=8,
                bbox=dict(boxstyle="round,pad=0.2", facecolor="white", alpha=0.8),
            )

    plt.xlabel("Method", fontsize=12)
    plt.ylabel(metric.upper(), fontsize=12)
    plt.title(f"Best Configurations Comparison ({metric.upper()})", fontsize=14)
    if dataset:
        plt.title(f"Best Configurations - {dataset} ({metric.upper()})", fontsize=14)

    plt.xticks(x_pos, methods, fontsize=9)
    plt.grid(axis="y", alpha=0.3)
    plt.tight_layout()
    plt.savefig(
        PLOTS_DIR / f"overall_comparison_{metric}.png", dpi=300, bbox_inches="tight"
    )
    plt.close()


def print_summary(data):
    """Print statistical summary."""
    print("\n" + "=" * 60)
    print("GRID SEARCH SUMMARY")
    print("=" * 60)

    # Count total configurations
    total_configs = sum(len(df) for df in data.values())
    print(f"Total configurations evaluated: {total_configs}")

    for metric in ["map", "P@10", "ndcg@100"]:
        print(f"\n{metric.upper()} Results:")
        print("-" * 40)

        # Baselines
        if "baseline" in data:
            print("Baseline Models:")
            for _, row in data["baseline"].iterrows():
                print(f"  {row['baseline']}: {row[metric]:.4f}")

        # MonoT5
        if "monot5" in data:
            print("\nBest MonoT5 Reranking:")
            for baseline in data["monot5"]["baseline"].unique():
                subset = data["monot5"][data["monot5"]["baseline"] == baseline]
                best = subset.loc[subset[metric].idxmax()]
                print(f"  {baseline}: {best[metric]:.4f} (depth={best['depth']})")

        # PRF
        if "prf" in data:
            print("\nBest PRF Configurations:")
            for strategy in data["prf"]["strategy"].unique():
                for rf_model in data["prf"]["rf_model"].unique():
                    subset = data["prf"][
                        (data["prf"]["strategy"] == strategy)
                        & (data["prf"]["rf_model"] == rf_model)
                    ]
                    if len(subset) > 0:
                        best = subset.loc[subset[metric].idxmax()]
                        print(
                            f"  {strategy} + {rf_model}: {best[metric]:.4f} "
                            f"(k={best['depth']}, e={best['e']}, λ={best['lambda']:.2f})"
                        )


def main():
    print("\n" + "=" * 60)
    print("GRID SEARCH VISUALIZATION")
    print("=" * 60 + "\n")

    # Extract dataset display name
    dataset_display = collection_name.upper() if collection_name else "DEFAULT"

    # Load data
    print("Loading data...")
    data = load_data()
    print()

    # Generate plots
    print("Generating plots...\n")

    metrics = ["map", "P@10", "ndcg@100"]

    for metric in metrics:
        print(f"Generating plots for {metric.upper()}...")

        # Overall comparison
        plot_overall_comparison(data, metric, dataset_display)

        # Baseline comparison
        if "baseline" in data:
            plot_baseline_comparison(data["baseline"], metric, dataset_display)

        # MonoT5 analysis
        if "monot5" in data:
            plot_monot5_depth_analysis(data["monot5"], metric, dataset_display)

        # PRF analysis
        if "prf" in data:
            plot_prf_lambda_impact(data["prf"], metric, dataset_display)
            plot_prf_rf_model_comparison(data["prf"], metric, dataset_display)

        print(f"✓ {metric.upper()} plots complete")

    print(f"\n✓ All plots saved in: {PLOTS_DIR}/")

    # Print summary
    print_summary(data)

    print("\n✓ Visualization complete!")


if __name__ == "__main__":
    main()
